/**
 * Job envelope (P08.01.01, ADR-0008): the one shape every background job carries.
 *
 * ID-only payload (P08 Security): the envelope names rows, never content — the
 * handler re-reads inside `withTenant`. One documented exception:
 * `degraded-capture` carries minimal callback fields (DB down at write time).
 *
 * Pure validation, no I/O. Deterministic: same object, same verdict.
 */

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/iu;

/** Job types known at PILOT. New types extend this union, never bypass it. */
export const JOB_TYPES = [
  'postcall-finalise',
  'notification-send',
  'sweep-run',
  'retention-purge',
  'import-structure',
  'reverify-sweep',
] as const;

export type JobType = (typeof JOB_TYPES)[number];

/** Queue per workload class (P08.01.02). FIFO only where ordering is load-bearing. */
export const JOB_QUEUES = {
  'postcall-finalise': 'voice-postcall',
  'notification-send': 'notifications',
  'sweep-run': 'sweeps',
  'retention-purge': 'sweeps',
  'import-structure': 'domain-events',
  'reverify-sweep': 'sweeps',
} as const satisfies Record<JobType, string>;

/**
 * Visibility timeout floor per queue: ≥ 6 × p99 handler time (P08.01.02).
 * Seconds. A timeout below the floor is a misconfiguration, rejected at
 * startup by checkVisibilityTimeout.
 */
export const QUEUE_VISIBILITY_FLOOR_S: Readonly<Record<string, number>> = {
  'voice-postcall': 360,
  notifications: 180,
  sweeps: 360,
  'domain-events': 180,
};

export interface JobEnvelope {
  readonly jobId: string;
  readonly type: JobType;
  readonly version: number;
  readonly organisationId: string | null;
  readonly correlationId: string;
  readonly traceContext: string | null;
  readonly attempt: number;
  readonly notBefore: string | null;
  readonly payload: Readonly<Record<string, string>>;
}

export interface EnvelopeLint {
  readonly ok: boolean;
  readonly errors: readonly string[];
}

function isUuid(value: unknown): value is string {
  return typeof value === 'string' && UUID_RE.test(value);
}

function isIsoInstant(value: unknown): value is string {
  if (typeof value !== 'string') return false;
  const ms = Date.parse(value);
  return Number.isFinite(ms);
}

/** ID-only payload: every value a UUID string (P08.01.01). Content travels via re-read, not queue. */
function checkPayload(payload: unknown): string[] {
  const errors: string[] = [];
  if (typeof payload !== 'object' || payload === null || Array.isArray(payload)) {
    return ['payload must be an object of id strings'];
  }
  for (const [key, value] of Object.entries(payload)) {
    if (key.length === 0 || key.length > 64)
      errors.push(`payload key "${key}" must be 1..64 chars`);
    if (!isUuid(value)) errors.push(`payload["${key}"] must be a uuid (ID-only payload)`);
  }
  return errors;
}

export function lintEnvelope(input: unknown): EnvelopeLint {
  const errors: string[] = [];
  if (typeof input !== 'object' || input === null) {
    return { ok: false, errors: ['envelope must be an object'] };
  }
  const env = input as Record<string, unknown>;
  if (!isUuid(env['jobId'])) errors.push('jobId must be a uuid (UUIDv7 generated by the app)');
  if (typeof env['type'] !== 'string' || !(JOB_TYPES as readonly string[]).includes(env['type'])) {
    errors.push(`type must be one of ${(JOB_TYPES as readonly string[]).join(', ')}`);
  }
  if (!Number.isInteger(env['version']) || (env['version'] as number) < 1) {
    errors.push('version must be an integer ≥ 1');
  }
  if (env['organisationId'] !== null && !isUuid(env['organisationId'])) {
    errors.push('organisationId must be a uuid or null (null = pre-tenant system work)');
  }
  if (!isUuid(env['correlationId'])) errors.push('correlationId must be a uuid');
  if (env['traceContext'] !== null && typeof env['traceContext'] !== 'string') {
    errors.push('traceContext must be a string or null');
  }
  if (!Number.isInteger(env['attempt']) || (env['attempt'] as number) < 0) {
    errors.push('attempt must be an integer ≥ 0');
  }
  if (env['notBefore'] !== null && !isIsoInstant(env['notBefore'])) {
    errors.push('notBefore must be an ISO instant or null');
  }
  errors.push(...checkPayload(env['payload']));
  return { ok: errors.length === 0, errors };
}

/** Queue name for a job type (P08.01.02). Unknown types throw — never a default queue. */
export function queueFor(type: JobType): string {
  const queue = (JOB_QUEUES as Record<string, string>)[type];
  if (queue === undefined) throw new RangeError(`unknown job type: ${String(type)}`);
  return queue;
}

/** Visibility-timeout floor check: configured seconds must cover ≥ 6 × p99 (P08.01.02). */
export function checkVisibilityTimeout(queue: string, seconds: number): void {
  const floor = QUEUE_VISIBILITY_FLOOR_S[queue];
  if (floor === undefined) throw new RangeError(`unknown queue: ${queue}`);
  if (!Number.isFinite(seconds) || seconds < floor) {
    throw new RangeError(`visibility timeout for ${queue} must be ≥ ${String(floor)}s`);
  }
}
